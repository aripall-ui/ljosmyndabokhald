"""Stamp index.html with a version so browsers always load the newest files.

Run before each commit:  python3 tools/version.py
Each JS/CSS file gets ?v=<hash of its contents> through an import map and the <link>/<script> tags.
"""
import hashlib, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
def h(p): return hashlib.sha1((root / p).read_bytes()).hexdigest()[:8]

files = sorted(str(p.relative_to(root)) for p in list(root.glob('js/*.js')) + list(root.glob('vendor/*.js')))
imports = ',\n'.join(f'      "./{f}": "./{f}?v={h(f)}"' for f in files)
block = ('  <!-- version:start (generated by tools/version.py) -->\n'
         f'  <link rel="stylesheet" href="css/app.css?v={h("css/app.css")}" />\n'
         f'  <link rel="stylesheet" href="css/themes.css?v={h("css/themes.css")}" />\n'
         f'  <script type="importmap">\n  {{\n    "imports": {{\n{imports}\n    }}\n  }}\n  </script>\n'
         '  <script>try { document.documentElement.dataset.palette = localStorage.getItem(\'palette\') || \'rokkur\'; } catch (e) {}</script>\n'
         f'  <script src="config.js?v={h("config.js")}"></script>\n'
         f'  <script src="vendor/jszip.min.js?v={h("vendor/jszip.min.js")}" defer></script>\n'
         f'  <script type="module" src="js/app.js?v={h("js/app.js")}"></script>\n'
         '  <!-- version:end -->')
html = (root / 'index.html').read_text()
if '<!-- version:start' in html:
    html = re.sub(r'  <!-- version:start.*?<!-- version:end -->', lambda m: block, html, flags=re.S)
else:
    start = html.index('  <link rel="stylesheet" href="css/app.css" />')
    end = html.index('<script type="module" src="js/app.js"></script>') + len('<script type="module" src="js/app.js"></script>')
    html = html[:start] + block + html[end:]
(root / 'index.html').write_text(html)
print('index.html stamped')
